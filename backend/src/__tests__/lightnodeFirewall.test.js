import { describe, expect, it } from 'vitest';
import { verifyLightNodeFirewall, buildLightNodeFirewallCommand } from '../services/infrastructure/lightnodeFirewall.js';

const policy = { managementSources: ['192.0.2.20', '2001:db8::20'] };
// Representative iptables-save filter output, including UFW's actual INPUT hooks.
// Profiles (including OpenSSH) are expanded to numeric rules by UFW in the kernel.
function firewallSnapshot(family = 4, dual = false) {
  const p = family === 4 ? 'ufw' : 'ufw6';
  const hooks = ['before-logging-input', 'before-input', 'after-input', 'after-logging-input', 'reject-input', 'track-input'];
  const source = family === 4 ? '192.0.2.20/32' : '2001:db8::20/128';
  return `# Generated by iptables-save v1.8.7\n*filter
:INPUT DROP [123:456]
:FORWARD DROP [0:0]
:OUTPUT ACCEPT [0:0]
${[...hooks, 'user-input'].map(c => `:${p}-${c} - [0:0]`).join('\n')}
${hooks.map(c => `-A INPUT -j ${p}-${c}`).join('\n')}
-A ${p}-before-input -i lo -j ACCEPT
-A ${p}-before-input -m conntrack --ctstate RELATED,ESTABLISHED -j ACCEPT
-A ${p}-before-input -m conntrack --ctstate INVALID -j DROP
-A ${p}-before-input -p ${family === 4 ? 'icmp' : 'ipv6-icmp'} -j ACCEPT
${family === 4 ? '-A ufw-before-input -p udp -m udp --sport 67 --dport 68 -j ACCEPT' : '-A ufw6-before-input -s fe80::/10 -d fe80::/10 -p udp -m udp --sport 547 --dport 546 -j ACCEPT'}
-A ${p}-before-input -j ${p}-user-input
-A ${p}-user-input -s ${source} -p tcp -m tcp --dport 22 -j ACCEPT
-A ${p}-user-input -s ${source} -p tcp -m tcp --dport 62050 -j ACCEPT
-A ${p}-user-input -p tcp -m tcp --dport 443 -j ACCEPT
${dual ? `-A ${p}-user-input -p tcp -m tcp --dport 8388 -j ACCEPT\n-A ${p}-user-input -p udp -m udp --dport 8388 -j ACCEPT\n` : ''}COMMIT
# Completed
`;
}
const verify = (ipv4, ipv6 = firewallSnapshot(6), protocols = ['vless']) =>
  verifyLightNodeFirewall({ ipv4, ipv6 }, policy, protocols);

describe('LightNode effective firewall policy', () => {
  it('rebuilds both families with DHCP client replies and ICMP, excluding discovery services', () => {
    const command = buildLightNodeFirewallCommand(policy, ['vless']);
    expect(command).toContain('-A ufw-before-input -p udp -m udp --sport 67 --dport 68 -j ACCEPT');
    expect(command).toContain('-A ufw6-before-input -s fe80::/10 -d fe80::/10 -p udp -m udp --sport 547 --dport 546 -j ACCEPT');
    expect(command).toContain('-A ufw6-before-input -p ipv6-icmp -j ACCEPT');
    expect(command).toContain("ufw allow from '2001:db8::20' to any port 22 proto tcp");
    expect(command).toContain("ufw allow from '2001:db8::20' to any port 62050 proto tcp");
    expect(command).not.toMatch(/5353|1900|ufw allow 22\/tcp|ufw allow 62050\/tcp/);
  });
  it.each([false, true])('accepts exactly the reviewed IPv4/IPv6 policy (dual=%s)', dual => {
    expect(verify(firewallSnapshot(4, dual), firewallSnapshot(6, dual), dual ? ['vless', 'shadowsocks'] : ['vless'])).toBe(true);
  });
  it.each([
    [4, '--sport 67 --dport 68', '--dport 68'],
    [4, '--sport 67 --dport 68', '--sport 67 --dport 69'],
    [6, '-s fe80::/10 -d fe80::/10 ', ''],
    [6, '--sport 547 --dport 546', '--dport 546'],
    [6, '--sport 547 --dport 546', '--sport 547 --dport 547'],
  ])('rejects broadened/changed IPv%s DHCP control rules %#', (family, before, after) => {
    const ipv4 = firewallSnapshot(4), ipv6 = firewallSnapshot(6);
    expect(() => verify(family === 4 ? ipv4.replace(before, after) : ipv4, family === 6 ? ipv6.replace(before, after) : ipv6))
      .toThrow('NODE_FIREWALL_POLICY_UNVERIFIED');
  });
  it.each([
    ['OpenSSH Anywhere', '-p tcp -m tcp --dport 22'],
    ['SSH range', '-p tcp -m multiport --dports 20:25'],
    ['foreign source', '-s 198.51.100.99/32 -p tcp -m tcp --dport 22'],
    ['management range', '-p tcp -m tcp --dport 62000:62100'],
    ['unreviewed port', '-p tcp -m tcp --dport 8443'],
    ['SSH UDP', '-s 192.0.2.20/32 -p udp -m udp --dport 22'],
  ])('rejects %s even when all required rules exist', (_, extra) => {
    expect(() => verify(firewallSnapshot().replace('COMMIT', `-A ufw-user-input ${extra} -j ACCEPT\nCOMMIT`)))
      .toThrow('NODE_FIREWALL_POLICY_UNVERIFIED');
  });
  it.each([
    '-p tcp -m tcp --dport 22',
    '-s 2001:db8::99/128 -p tcp -m tcp --dport 62050',
    '-s 2001:db8::/64 -p tcp -m tcp --dport 22',
    '-p tcp -m multiport --dports 22,62050',
  ])('rejects unrestricted/foreign/range IPv6 management: %s', extra => {
    expect(() => verify(firewallSnapshot(), firewallSnapshot(6).replace('COMMIT', `-A ufw6-user-input ${extra} -j ACCEPT\nCOMMIT`)))
      .toThrow('NODE_FIREWALL_POLICY_UNVERIFIED');
  });
  it('does not allow IPv6 management when policy has only IPv4 sources', () => {
    expect(() => verifyLightNodeFirewall({ ipv4: firewallSnapshot(), ipv6: firewallSnapshot(6) }, { managementSources: ['192.0.2.20'] }, ['vless']))
      .toThrow('NODE_FIREWALL_POLICY_UNVERIFIED');
    const ipv6 = firewallSnapshot(6).split('\n').filter(l => !l.includes('-s 2001:db8::20/128')).join('\n');
    expect(verifyLightNodeFirewall({ ipv4: firewallSnapshot(), ipv6 }, { managementSources: ['192.0.2.20'] }, ['vless'])).toBe(true);
  });
  it.each([
    s => s.replace('--dport 62050', '--dport 62051'),
    s => s.replace('-p tcp -m tcp --dport 443', '-p udp -m udp --dport 443'),
    s => s.replace(':INPUT DROP', ':INPUT ACCEPT'),
    s => s.replace('-A INPUT -j ufw-before-input', '-A INPUT -j ACCEPT'),
    s => s.replace('-A ufw-before-input -i lo', '-A ufw-before-input'),
    s => s.replace('COMMIT', '-A ufw-after-input -p tcp -m tcp --dport 22 -j ACCEPT\nCOMMIT'),
    s => s.replace('-A ufw-before-input -j ufw-user-input\n', ''),
    s => s.replace('COMMIT', '-A ufw-user-input -j mystery\nCOMMIT'),
    s => s.replace('COMMIT', '-A ufw-user-input -p tcp --dport\nCOMMIT'),
    s => s.replace(':ufw-user-input - [0:0]', ':ufw-user-input - [0:0]\n:ufw-user-input - [0:0]'),
    s => s.replace('COMMIT', '-A undeclared -j ACCEPT\nCOMMIT'),
    s => s.replace('COMMIT', ''),
    s => s + '*filter\nCOMMIT\n',
    () => 'Status: active\nOpenSSH ALLOW Anywhere',
    () => '',
  ])('fails closed on missing, bypassed, unsupported or malformed effective policy %#', mutate => {
    expect(() => verify(mutate(firewallSnapshot()))).toThrow('NODE_FIREWALL_POLICY_UNVERIFIED');
  });
  it('requires SS TCP and UDP only in the dual profile', () => {
    expect(() => verify(firewallSnapshot(4, true))).toThrow('NODE_FIREWALL_POLICY_UNVERIFIED');
    expect(() => verify(firewallSnapshot(4, true).replace('-A ufw-user-input -p udp -m udp --dport 8388 -j ACCEPT\n', ''), firewallSnapshot(6, true), ['vless', 'shadowsocks']))
      .toThrow('NODE_FIREWALL_POLICY_UNVERIFIED');
  });
  it.each([undefined, '', 'Status: inactive', '*filter\nCOMMIT'])('requires independently readable IPv6 rules: %s', ipv6 => {
    expect(() => verifyLightNodeFirewall({ ipv4: firewallSnapshot(), ipv6 }, policy, ['vless'])).toThrow('NODE_FIREWALL_POLICY_UNVERIFIED');
  });
  it('normalizes equivalent host IPv6 addresses and rejects unsafe source inputs', () => {
    expect(verify(firewallSnapshot(), firewallSnapshot(6).replaceAll('2001:db8::20/128', '2001:0db8:0:0:0:0:0:20/128'))).toBe(true);
    for (const source of ["x'; echo unsafe", '0.0.0.0/0', '::/0']) {
      expect(() => buildLightNodeFirewallCommand({ managementSources: [source] }, ['vless'])).toThrow('NODE_FIREWALL_POLICY_UNVERIFIED');
    }
  });
});
