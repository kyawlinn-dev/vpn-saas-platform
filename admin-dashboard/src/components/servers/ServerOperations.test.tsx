import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { ServerOperationDialog } from './ServerOperationDialog';
import { ServerOperationProgress } from './ServerOperationProgress';
import { serverOperationsApi, type OperationQuote, type ServerOperation } from '@/features/serverOperations/api';
import type { Server } from '@/types/api';
vi.mock('@/features/serverOperations/api', () => ({ serverOperationsApi: { quote: vi.fn(), create: vi.fn(), get: vi.fn(), control: vi.fn() } }));
const options = [{ id: 'digitalocean' as const, regions: [{ id: 'sgp1', label: 'Singapore', plans: [{ id: 'small', label: 'Small' }] }] }];
const quote: OperationQuote = { id: 'quote', kind: 'add', source_server_id: null, destination_server_id: null, supported_protocols: ['vless'], temporary_billing_overlap: false, expiresAt: '2099-01-01', price: { provider: 'digitalocean', region: 'sgp1', planId: 'small', recurringAmount: 6, currency: 'USD', trafficTerms: { included: 1000, unit: 'GB', overageAmount: null } } };
const operation: ServerOperation = { id: 'operation', kind: 'add', status: 'running', phase: 'verifying', source_server_id: null, destination_server_id: null, counts: { total: 0, verified: 0 }, price: null, created_at: null, updated_at: null, error_code: null, ongoing_charges: [], allowed_actions: [] };
describe('server operation controls', () => {
  it('labels completed LightNode billing proof as package-only',()=>{
    render(<ServerOperationProgress initial={{...operation,status:'completed',phase:'finalizing',billing_assurance:{scope:'instance-package',external_attachments_verified:false}}} />);
    expect(screen.getByText('Instance package verified. Detached resources and other account charges were not checked.')).toBeTruthy();
  });
  beforeEach(() => { sessionStorage.clear(); vi.mocked(serverOperationsApi.quote).mockResolvedValue(quote); vi.mocked(serverOperationsApi.create).mockResolvedValue(operation); vi.mocked(serverOperationsApi.get).mockResolvedValue(operation); });
  afterEach(() => { cleanup(); vi.clearAllMocks(); });
  it('reviews VLESS retirement without a destination picker and requires deletion approval', async () => {
    const source={id:'source',name:'Singapore #6',supported_protocols:['vless']} as Server;
    vi.mocked(serverOperationsApi.quote).mockResolvedValue({...quote,kind:'move_retire',retire_only:true,source_server_id:source.id,destination_server_id:'fallback',price:null});
    render(<ServerOperationDialog mode="move_retire" source={source} servers={[source]} options={options} onClose={()=>{}} onCreated={()=>{}} />);
    expect(screen.getByRole('heading',{name:'Retire Server'})).toBeTruthy();
    expect(screen.queryByRole('combobox',{name:'Destination'})).toBeNull();
    fireEvent.click(screen.getByRole('button',{name:'Review Retirement'}));
    await screen.findByText('No new VPS purchase');
    expect(serverOperationsApi.quote).toHaveBeenCalledWith({kind:'move_retire',source_server_id:'source',retire_only:true});
    expect((screen.getByRole('button',{name:'Retire Server'}) as HTMLButtonElement).disabled).toBe(true);
    fireEvent.click(screen.getByLabelText('Approve deletion of the source VPS after verification'));
    expect((screen.getByRole('button',{name:'Retire Server'}) as HTMLButtonElement).disabled).toBe(false);
  });
  it('recovers an uncertain retirement with the same intent and idempotency key without source props', async () => {
    vi.mocked(serverOperationsApi.create).mockRejectedValueOnce(new Error('timeout'));
    const source={id:'source',name:'Singapore #6',supported_protocols:['vless']} as Server;
    const reviewed={...quote,kind:'move_retire' as const,retire_only:true,source_server_id:source.id,destination_server_id:'fallback',price:null};
    vi.mocked(serverOperationsApi.quote).mockResolvedValue(reviewed);
    const first=render(<ServerOperationDialog mode="move_retire" source={source} servers={[source]} options={options} onClose={()=>{}} onCreated={()=>{}} />);
    fireEvent.click(screen.getByRole('button',{name:'Review Retirement'}));
    await screen.findByText('No new VPS purchase');
    fireEvent.click(screen.getByLabelText('Approve deletion of the source VPS after verification'));
    fireEvent.click(screen.getByRole('button',{name:'Retire Server'}));
    await screen.findByRole('alert');
    const original=vi.mocked(serverOperationsApi.create).mock.calls[0];
    first.unmount();
    render(<ServerOperationDialog mode="move_retire" servers={[]} options={options} onClose={()=>{}} onCreated={()=>{}} />);
    expect(screen.queryByRole('combobox',{name:'Destination'})).toBeNull();
    fireEvent.click(screen.getByRole('button',{name:'Retire Server'}));
    await waitFor(()=>expect(serverOperationsApi.create).toHaveBeenCalledTimes(2));
    expect(vi.mocked(serverOperationsApi.create).mock.calls[1]).toEqual(original);
    expect(serverOperationsApi.quote).toHaveBeenCalledTimes(1);
  });
  it('allows a fresh retirement review when the chosen fallback becomes unavailable before admission', async () => {
    vi.mocked(serverOperationsApi.create).mockRejectedValueOnce({response:{status:409,data:{code:'DESTINATION_NOT_READY'}}});
    const source={id:'source',name:'Singapore #6',supported_protocols:['vless']} as Server;
    vi.mocked(serverOperationsApi.quote).mockResolvedValue({...quote,kind:'move_retire',retire_only:true,source_server_id:'source',destination_server_id:'fallback',price:null});
    render(<ServerOperationDialog mode="move_retire" source={source} servers={[source]} options={options} onClose={()=>{}} onCreated={()=>{}} />);
    fireEvent.click(screen.getByRole('button',{name:'Review Retirement'}));
    await screen.findByText('No new VPS purchase');
    fireEvent.click(screen.getByLabelText('Approve deletion of the source VPS after verification'));
    fireEvent.click(screen.getByRole('button',{name:'Retire Server'}));
    await screen.findByRole('alert');
    expect(sessionStorage.getItem('novanet:pending-server-operation')).toBeNull();
    expect((screen.getByRole('button',{name:'Review Retirement'}) as HTMLButtonElement).disabled).toBe(false);
  });
  it('preserves retirement intent when a reopened pending request is explicitly rejected', async () => {
    const reviewed={...quote,kind:'move_retire' as const,retire_only:true,source_server_id:'source',destination_server_id:'fallback',price:null};
    sessionStorage.setItem('novanet:pending-server-operation',JSON.stringify({key:'original',request:{quote_id:'quote',confirm_delete_source:true},quote:reviewed,
      choice:{kind:'move_retire',source_server_id:'source',retire_only:true}}));
    vi.mocked(serverOperationsApi.create).mockRejectedValueOnce({response:{status:409,data:{code:'DESTINATION_NOT_READY'}}});
    vi.mocked(serverOperationsApi.quote).mockResolvedValue(reviewed);
    render(<ServerOperationDialog mode="move_retire" servers={[]} options={options} onClose={()=>{}} onCreated={()=>{}} />);
    fireEvent.click(screen.getByRole('button',{name:'Retire Server'}));
    await screen.findByRole('alert');
    expect(screen.getByRole('heading',{name:'Retire Server'})).toBeTruthy();
    expect(screen.queryByRole('combobox',{name:'Destination'})).toBeNull();
    fireEvent.click(screen.getByRole('button',{name:'Review Retirement'}));
    await waitFor(()=>expect(serverOperationsApi.quote).toHaveBeenCalledWith({kind:'move_retire',source_server_id:'source',retire_only:true}));
  });
  it('requires a reviewed quote and cost confirmation, then prevents double submission', async () => {
    let finish!: (value: ServerOperation) => void;
    vi.mocked(serverOperationsApi.create).mockReturnValue(new Promise(resolve => { finish = resolve; }));
    render(<ServerOperationDialog mode="add" servers={[]} options={options} onClose={() => {}} onCreated={() => {}} />);
    fireEvent.click(screen.getByRole('button', { name: 'Review Quote' }));
    await screen.findByText('6.00 USD / month');
    const submit = screen.getByRole('button', { name: 'Add Server' }) as HTMLButtonElement;
    expect(submit.disabled).toBe(true);
    fireEvent.click(screen.getByLabelText('Approve recurring cost'));
    fireEvent.click(submit); fireEvent.click(submit);
    expect(serverOperationsApi.create).toHaveBeenCalledTimes(1);
    finish(operation);
  });
  it('requires overlap and deletion approval before replacement', async () => {
    vi.mocked(serverOperationsApi.quote).mockResolvedValue({ ...quote, kind: 'replace', source_server_id: 'source', temporary_billing_overlap: true });
    const source = { id: 'source', name: 'Source', supported_protocols: ['vless'] } as Server;
    render(<ServerOperationDialog mode="replace" source={source} servers={[source]} options={options} onClose={() => {}} onCreated={() => {}} />);
    fireEvent.click(screen.getByRole('button', { name: 'Review Quote' }));
    await screen.findByLabelText('Approve recurring cost');
    fireEvent.click(screen.getByLabelText('Approve recurring cost'));
    expect((screen.getByRole('button', { name: 'Replace Server' }) as HTMLButtonElement).disabled).toBe(true);
    fireEvent.click(screen.getByLabelText('Approve temporary two-VPS billing'));
    fireEvent.click(screen.getByLabelText('Approve deletion of the source VPS after verification'));
    expect((screen.getByRole('button', { name: 'Replace Server' }) as HTMLButtonElement).disabled).toBe(false);
  });
  it('filters VLESS-only targets out of dual-protocol moves regardless of legacy tier', () => {
    const source = { id: 'source', name: 'Source', supported_protocols: ['shadowsocks', 'vless'], environment: 'development', access_pool_id: 'pool' } as Server;
    const base = { environment: 'development', access_pool_id: 'pool', status: 'active', is_active: true };
    const targets = [{ ...base, id: 'vless', name: 'VLESS only', supported_protocols: ['vless'] }, { ...base, id: 'dual', name: 'Public dual', server_tier: 'trial', supported_protocols: ['shadowsocks', 'vless'] }] as Server[];
    render(<ServerOperationDialog mode="move_retire" source={source} servers={[source, ...targets]} options={options} onClose={() => {}} onCreated={() => {}} />);
    expect(screen.queryByRole('option', { name: 'VLESS only' })).toBeNull(); expect(screen.getByRole('option', { name: 'Public dual' })).toBeTruthy();
  });
  it('keeps billing warnings visible and offers only backend-approved recovery actions', async () => {
    const pending = { ...operation, phase: 'cleanup_pending', status: 'blocked', ongoing_charges: [{ id: 'volume', type: 'volume', amount: null, currency: null }], allowed_actions: ['resume'] as ('resume' | 'cancel')[] };
    vi.mocked(serverOperationsApi.get).mockResolvedValue(pending);
    vi.mocked(serverOperationsApi.control).mockResolvedValue(operation);
    render(<ServerOperationProgress initial={pending} />);
    expect(screen.getByText('Ongoing charges may remain')).toBeTruthy();
    expect(screen.queryByRole('button', { name: 'Cancel' })).toBeNull();
    fireEvent.click(screen.getByRole('button', { name: 'Resume' }));
    await waitFor(() => expect(serverOperationsApi.control).toHaveBeenCalledWith('operation', 'resume'));
  });
  it('retries an uncertain submission after quote expiry using the identical key and body', async () => {
    vi.mocked(serverOperationsApi.create).mockRejectedValueOnce(new Error('timeout'));
    const props = { mode: 'add' as const, servers: [], options, onClose: () => {}, onCreated: vi.fn() };
    const first = render(<ServerOperationDialog {...props} />);
    fireEvent.click(screen.getByRole('button', { name: 'Review Quote' }));
    await screen.findByLabelText('Approve recurring cost');
    fireEvent.click(screen.getByLabelText('Approve recurring cost'));
    fireEvent.click(screen.getByRole('button', { name: 'Add Server' }));
    await screen.findByRole('alert');
    const [body, key] = vi.mocked(serverOperationsApi.create).mock.calls[0];
    first.unmount();
    const stored = JSON.parse(sessionStorage.getItem('novanet:pending-server-operation')!);
    stored.quote.expiresAt = '2000-01-01';
    sessionStorage.setItem('novanet:pending-server-operation', JSON.stringify(stored));
    render(<ServerOperationDialog {...props} />);
    fireEvent.click(screen.getByRole('button', { name: 'Add Server' }));
    await waitFor(() => expect(serverOperationsApi.create).toHaveBeenCalledTimes(2));
    expect(vi.mocked(serverOperationsApi.create).mock.calls[1]).toEqual([body, key]);
  });
  it('refreshes inventory on completion and aborts polling on unmount', async () => {
    const onComplete = vi.fn();
    vi.mocked(serverOperationsApi.get).mockResolvedValue({ ...operation, status: 'completed' });
    const view = render(<ServerOperationProgress initial={operation} onComplete={onComplete} />);
    await waitFor(() => expect(onComplete).toHaveBeenCalledTimes(1));
    const signal = vi.mocked(serverOperationsApi.get).mock.calls[0][1];
    view.unmount();
    expect(signal?.aborted).toBe(true);
  });
  it('allows a fresh quote after an explicitly rejected expired request', async () => {
    vi.mocked(serverOperationsApi.create).mockRejectedValueOnce({ response: { status: 409, data: { code: 'QUOTE_EXPIRED' } } });
    render(<ServerOperationDialog mode="add" servers={[]} options={options} onClose={() => {}} onCreated={() => {}} />);
    fireEvent.click(screen.getByRole('button', { name: 'Review Quote' }));
    await screen.findByLabelText('Approve recurring cost');
    fireEvent.click(screen.getByLabelText('Approve recurring cost'));
    fireEvent.click(screen.getByRole('button', { name: 'Add Server' }));
    await screen.findByRole('alert');
    expect((screen.getByRole('button', { name: 'Review Quote' }) as HTMLButtonElement).disabled).toBe(false);
    expect(sessionStorage.getItem('novanet:pending-server-operation')).toBeNull();
  });
});
