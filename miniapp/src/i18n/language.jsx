const LanguageContext = createContext(null);

function normalizeLanguage(value) {
  return LANGUAGE_OPTIONS.some((option) => option.code === value)
    ? value
    : DEFAULT_LANGUAGE;
}

function getInitialLanguage() {
  if (typeof window === "undefined") return DEFAULT_LANGUAGE;

  try {
    return normalizeLanguage(window.localStorage.getItem(STORAGE_KEY));
  } catch {
    return DEFAULT_LANGUAGE;
  }
}

export function translate(language, key, values = {}) {
  const text = DICTIONARY[language]?.[key] ?? DICTIONARY.EN[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => values[name] ?? "");
}

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(getInitialLanguage);

  useEffect(() => {
    document.documentElement.lang = language === "MM" ? "my" : "en";

    try {
      window.localStorage.setItem(STORAGE_KEY, language);
    } catch {
      // Ignore private-mode or storage-disabled WebViews.
    }
  }, [language]);

  const value = useMemo(() => {
    const currentLanguage =
      LANGUAGE_OPTIONS.find((option) => option.code === language) ?? LANGUAGE_OPTIONS[0];

    return {
      currentLanguage,
      language,
      languages: LANGUAGE_OPTIONS,
      setLanguage: (nextLanguage) => setLanguageState(normalizeLanguage(nextLanguage)),
      t: (key, values) => translate(language, key, values),
    };
  }, [language]);

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage must be used inside LanguageProvider");
  }
  return context;
}
